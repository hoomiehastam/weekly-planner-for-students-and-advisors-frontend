export default function Ico({ e, className = '' }) {
  if (!e) return null;
  const rawKey = String(e);
  const cleanKey = rawKey.replace(/[\uFE0F\uFE0E]/g, '');
  const name = MAP[rawKey] || MAP[cleanKey] || MAP[cleanKey.replace(/\u200D/g, '')];
  if (!name) {
    return <i className={`ti ti-point ico ${className}`.trim()} aria-hidden="true" />;
  }
  return <i className={`ti ti-${name} ico ${className}`.trim()} aria-hidden="true" />;
}
